using Security;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace Plugin.Maui.NearbyConnectivity;

// The local half of the DTLS handshake MCSession runs when it is given an identity. Nothing here
// authenticates anybody by itself: the certificate is self-signed and minted fresh per session, so
// it proves only that whoever finished the handshake holds its private key. That is exactly what
// makes the pair of fingerprints worth comparing — a relay has to terminate DTLS on both sides and
// therefore presents its own key to each person, which changes what they read out.
//
// RSA-2048, not EC. P-256 fails the handshake outright on Multipeer with SSLHandshake error -9834,
// with or without key-usage, EKU, basic-constraints and SKI extensions; Multipeer's DTLS is
// SecureTransport-era. Network framework may accept EC, so this choice is not portable forward.
static class EphemeralIdentity
{
    // Only long enough to cover one session's handshake, with room for clock skew between the two
    // devices. A certificate is minted per session and discarded with it.
    static readonly TimeSpan s_skew = TimeSpan.FromDays(1);

    const int KeySizeBits = 2048;

    // The private key is generated by Security.framework, is not permanent, and never leaves it:
    // no managed RSA, no PKCS#12 blob, no keychain. Only the public key and the certificate's
    // signature cross into .NET.
    [SuppressMessage(
        "Reliability",
        "CA2000:Dispose objects before losing scope",
        Justification = "An out NSError is a borrowed autoreleased object; its managed wrapper holds no " +
            "resource that needs early release.")]
    internal static SecIdentity Create()
    {
        using var privateKey = SecKey.CreateRandomKey(
            new SecKeyGenerationParameters
            {
                KeyType = SecKeyType.RSA,
                KeySizeInBits = KeySizeBits,
                IsPermanent = false,
            },
            out var keyError)
            ?? throw Failure(keyError);

        using var publicKey = privateKey.GetPublicKey() ?? throw Failure(null);
        using var publicKeyData = publicKey.GetExternalRepresentation(out var exportError)
            ?? throw Failure(exportError);
        using var rsaPublicKey = RSA.Create();
        rsaPublicKey.ImportRSAPublicKey(publicKeyData.ToArray(), out _);

        var name = new X500DistinguishedName("CN=PMNC");
        var request = new CertificateRequest(name, rsaPublicKey, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
        var now = DateTimeOffset.UtcNow;

        using var certificate = request.Create(
            name,
            new SecKeySignatureGenerator(privateKey, rsaPublicKey),
            now - s_skew,
            now + s_skew,
            RandomNumberGenerator.GetBytes(16));

        using var secCertificate = new SecCertificate(certificate);

        return SecIdentity.Create(secCertificate, privateKey) ?? throw Failure(null);
    }

    // The peer's certificate as MPC hands it over, reduced to the value both sides can compare.
    internal static byte[] Fingerprint(SecCertificate certificate)
        => SHA256.HashData(certificate.DerData.ToArray());

    static NearbyException Failure(NSError? error)
        => new($"Failed to create the session's ephemeral identity. {error?.LocalizedDescription}".TrimEnd());

    sealed class SecKeySignatureGenerator(SecKey privateKey, RSA publicKey) : X509SignatureGenerator
    {
        readonly X509SignatureGenerator _publicPart = CreateForRSA(publicKey, RSASignaturePadding.Pkcs1);

        public override byte[] GetSignatureAlgorithmIdentifier(HashAlgorithmName hashAlgorithm)
            => _publicPart.GetSignatureAlgorithmIdentifier(hashAlgorithm);

        [SuppressMessage(
            "Reliability",
            "CA2000:Dispose objects before losing scope",
            Justification = "An out NSError is a borrowed autoreleased object; its managed wrapper holds no " +
                "resource that needs early release.")]
        public override byte[] SignData(byte[] data, HashAlgorithmName hashAlgorithm)
        {
            using var message = NSData.FromArray(data);
            using var signature = privateKey.CreateSignature(
                SecKeyAlgorithm.RsaSignatureMessagePkcs1v15Sha256,
                message,
                out var error);

            return signature?.ToArray() ?? throw Failure(error);
        }

        protected override PublicKey BuildPublicKey() => _publicPart.PublicKey;
    }
}
