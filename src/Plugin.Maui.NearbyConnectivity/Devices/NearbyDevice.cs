namespace Plugin.Maui.NearbyConnectivity;

/// <summary>
/// Represents a remote device discovered by, or connected to, an <see cref="INearbyConnectivity"/>.
/// </summary>
/// <remarks>
/// <para>
/// <b>An instance is an immutable snapshot.</b> It describes what was true the moment it was
/// produced and never changes afterwards. When a device's status changes, the session publishes a
/// new instance through <see cref="INearbyConnectivity.DeviceChanged"/>.
/// The instance you are already holding keeps reporting the old status. Hold a device only as long
/// as the change that delivered it, or re-read the current one from
/// <see cref="INearbyConnectivity.Devices"/>.
/// </para>
/// <para>
/// <b>Equality is <see cref="Id"/> alone</b>, so two snapshots of one device compare equal however
/// their statuses differ.
/// </para>
/// <para>
/// <b>The verbs resolve live, the data does not.</b> <see cref="ConnectAsync"/>,
/// <see cref="DisconnectAsync"/> and <see cref="Connection"/> look the device up in the session at
/// the moment they are called, so acting on a stale snapshot is safe. The tap that lands a second
/// after a row was bound still acts on what is true now. Only the properties are frozen.
/// </para>
/// </remarks>
/// <seealso href="https://phunkeler.github.io/Plugin.Maui.NearbyConnectivity/docs/connect.html">Accept and make connections</seealso>
public sealed class NearbyDevice
{
    /// <summary>
    /// Initializes a new instance of the <see cref="NearbyDevice"/> class.
    /// </summary>
    /// <param name="id">
    /// A unique identifier for the device, valid within the current session. Generated by this
    /// plugin, with the same shape on every platform. See <see cref="Id"/>.
    /// </param>
    /// <param name="presence">
    /// What the remote device shows: its display name and its application-defined info, exactly as
    /// it sent them.
    /// </param>
    /// <remarks>
    /// For tests of code that consumes devices, such as a view model fed by a fake
    /// <see cref="INearbyConnectivity"/>. A device built here belongs to no session:
    /// <see cref="Connection"/>, <see cref="Request"/> and <see cref="ConnectExpiresAt"/> are
    /// <see langword="null"/>, and <see cref="ConnectAsync"/> and <see cref="DisconnectAsync"/>
    /// throw <see cref="InvalidOperationException"/>. A session never acts on a device it did not
    /// produce.
    /// </remarks>
    /// <exception cref="ArgumentNullException">
    /// <paramref name="id"/> or <paramref name="presence"/> is <see langword="null"/>.
    /// </exception>
    public NearbyDevice(string id, NearbyPresence presence)
    {
        ArgumentNullException.ThrowIfNull(id);
        ArgumentNullException.ThrowIfNull(presence);

        Id = id;
        Presence = presence;
    }

    /// <summary>
    /// The session this device acts through, attached when the device enters the device set.
    /// </summary>
    /// <remarks>
    /// A field rather than a constructor parameter because <c>PeerLookup</c> mints devices inside
    /// the transport, below the session that owns the verbs. The layer that mints a device
    /// attaches the gateway, and every later snapshot is a <see langword="with"/> copy, which
    /// carries the field along. A device built outside that path has no gateway and throws.
    /// </remarks>
    internal INearbyDeviceGateway? Gateway { get; init; }

    /// <summary>
    /// Gets the unique identifier for this device.
    /// </summary>
    /// <value>
    /// An identifier unique within the current session. This is the sole basis for
    /// <see cref="Equals(NearbyDevice?)"/>.
    /// </value>
    /// <remarks>
    /// <para>
    /// <b>Generated by this plugin, not by the platform.</b> Sixteen hexadecimal characters from a
    /// cryptographically secure random source, with the same shape on Android and iOS. Neither
    /// platform's own identifier reaches this property or any other part of the public API.
    /// Google's endpoint id and Apple's peer handle stay internal.
    /// </para>
    /// <para>
    /// <b>Opaque and session-scoped.</b> It carries no device information, is not derived from the
    /// display name or any hardware identifier, and does not survive the session: the same physical
    /// device gets a different value next time. Treat it as a handle for correlating events within
    /// one run, not as a stable device identity to persist, and not as an anonymous statistic to
    /// publish, since it does identify a device for the life of the session.
    /// </para>
    /// </remarks>
    public string Id { get; }

    /// <summary>
    /// Gets what this device shows to devices in range: its display name and its
    /// application-defined info.
    /// </summary>
    /// <value>
    /// The remote device's presence as it sent it. Never <see langword="null"/>. The name is at
    /// most <see cref="NearbyPresence.MaxDisplayNameBytes"/> UTF-8 bytes and may be empty; the info
    /// is empty when the peer sent none.
    /// </value>
    /// <remarks>
    /// <b>Remote-chosen, untrusted input.</b> Both members are bounded in length and rewritten in
    /// no other way, so the name may contain bidi controls or separators and the info is bytes to
    /// validate before parsing. Treat the presence as a label to filter and display by, never as an
    /// identifier or a credential. Use <see cref="Id"/> to correlate.
    /// </remarks>
    public NearbyPresence Presence { get; internal init; }

    /// <summary>
    /// Gets where this device sits in its lifecycle, as of this snapshot.
    /// </summary>
    /// <value>
    /// One of the <see cref="NearbyDeviceStatus"/> values. The default is
    /// <see cref="NearbyDeviceStatus.Visible"/>. Set it when building a device for a test.
    /// </value>
    public NearbyDeviceStatus Status { get; init; }

    /// <summary>
    /// Gets the inbound connection request outstanding from this device, if one is.
    /// </summary>
    /// <value>
    /// The request while <see cref="Status"/> is <see cref="NearbyDeviceStatus.RequestReceived"/>,
    /// otherwise <see langword="null"/>. Its <see cref="NearbyConnectionRequest.ExpiresAt"/>,
    /// <see cref="NearbyConnectionRequest.ExpiresIn"/> and
    /// <see cref="NearbyConnectionRequest.Expired"/> carry the offer's deadline in the shapes a
    /// view needs, from the one object that owns it.
    /// </value>
    /// <remarks>
    /// Resolved against the session on every read, exactly like <see cref="Connection"/>, so a row
    /// bound to a snapshot taken earlier still answers the current request.
    /// </remarks>
    public NearbyConnectionRequest? Request
        => Gateway is { } gateway && gateway.TryGetRequest(Id, out var request)
            ? request
            : null;

    /// <summary>
    /// Gets when the outbound handshake to this device stops waiting, if one is in flight.
    /// </summary>
    /// <value>
    /// The deadline while <see cref="Status"/> is <see cref="NearbyDeviceStatus.Connecting"/>
    /// because the local device called <see cref="ConnectAsync"/>; otherwise <see langword="null"/>.
    /// The initiator-side counterpart of <see cref="NearbyConnectionRequest.ExpiresAt"/>: the local
    /// <see cref="NearbyOptions.OfferWindow"/>, clamped, measured from when the handshake began.
    /// </value>
    /// <remarks>
    /// <para>
    /// Resolved against the session on every read, exactly like <see cref="Request"/> and
    /// <see cref="Connection"/>, so it reports the deadline the handshake is actually running under
    /// rather than a copy a caller recomputed and now has to keep in step. It goes
    /// <see langword="null"/> the moment the handshake settles, however it settled.
    /// </para>
    /// <para>
    /// <see langword="null"/> while accepting an inbound request. That side's deadline is
    /// <see cref="NearbyConnectionRequest.ExpiresAt"/>, on the request itself.
    /// </para>
    /// </remarks>
    public DateTimeOffset? ConnectExpiresAt
        => Gateway is { } gateway && gateway.TryGetConnectDeadline(Id, out var deadline)
            ? deadline
            : null;

    /// <summary>
    /// Gets the open connection to this device, or <see langword="null"/> if there is none.
    /// </summary>
    /// <value>
    /// The live connection if one is open right now; otherwise <see langword="null"/>. Resolved on
    /// every read against the session's connection table, so it is current even when read from a
    /// snapshot taken some time ago.
    /// </value>
    /// <remarks>
    /// A device that is not part of a session's device set, one constructed directly in a test,
    /// always reports <see langword="null"/> rather than throwing, because "is there a connection"
    /// has a correct answer for a device with no session: no.
    /// </remarks>
    public NearbyConnection? Connection
        => Gateway is { } gateway && gateway.TryGetConnection(Id, out var connection)
            ? connection
            : null;

    /// <summary>
    /// Opens a connection to this device, or returns the one already open.
    /// </summary>
    /// <param name="cancellationToken">A token to stop waiting for the handshake.</param>
    /// <returns>
    /// The established connection, the same instance <see cref="Connection"/> returns.
    /// </returns>
    /// <remarks>
    /// <para>
    /// The device is resolved in the session by <see cref="Id"/> as the call is made, so a snapshot
    /// that has since gone stale still connects to the right device, or fails because the session
    /// no longer knows it.
    /// </para>
    /// <para>
    /// <b>Convergent.</b> If a connection is already open it is returned; if a handshake is already
    /// in flight this joins it; if the device has already sent a request of its own, that request
    /// is accepted. Connecting twice is not an error.
    /// </para>
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    /// This device did not come from a session's device set, so it has nothing to act through.
    /// </exception>
    /// <exception cref="NearbyConnectException">
    /// The handshake did not produce a connection. Branch on
    /// <see cref="NearbyConnectException.Reason"/>: <see cref="NearbyConnectFailure.DeviceUnknown"/>
    /// when the device is no longer known to the session, <see cref="NearbyConnectFailure.TimedOut"/>
    /// when <see cref="NearbyOptions.OfferWindow"/> elapsed, or
    /// <see cref="NearbyConnectFailure.Failed"/> otherwise.
    /// </exception>
    /// <exception cref="OperationCanceledException">
    /// <paramref name="cancellationToken"/> was canceled.
    /// </exception>
    /// <example>
    /// <code language="csharp">
    /// try
    /// {
    ///     var connection = await device.ConnectAsync(cancellationToken);
    ///     await connection.SendAsync(Encoding.UTF8.GetBytes("hello"), cancellationToken);
    /// }
    /// catch (NearbyConnectException ex) when (ex.Reason is NearbyConnectFailure.TimedOut)
    /// {
    ///     Status = $"{device.Presence.DisplayName} did not answer.";
    /// }
    /// </code>
    /// </example>
    public Task<NearbyConnection> ConnectAsync(CancellationToken cancellationToken = default)
        => RequireGateway().ConnectAsync(Id, cancellationToken);

    /// <summary>
    /// Closes the connection to this device. Does nothing if there is none.
    /// </summary>
    /// <returns>A task that completes once the connection is released.</returns>
    /// <remarks>
    /// Resolved live by <see cref="Id"/> for the same reason <see cref="ConnectAsync"/> is. Closes
    /// the connection for every holder, not just this caller — see
    /// <see cref="NearbyConnection.CloseAsync"/>.
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    /// This device did not come from a session's device set, so it has nothing to act through.
    /// </exception>
    public Task DisconnectAsync()
        => RequireGateway().DisconnectAsync(Id);

    INearbyDeviceGateway RequireGateway()
        => Gateway ?? throw new InvalidOperationException(
            $"This {nameof(NearbyDevice)} was not produced by a session, so it cannot act on one. "
            + $"Read devices from {nameof(INearbyConnectivity)}.{nameof(INearbyConnectivity.Devices)} "
            + "or from a change, request, or connection the session published.");

    /// <summary>
    /// A copy of this device with the given lifecycle state, what the session publishes when a
    /// device changes.
    /// </summary>
    // Do not make this a record to get `with` back. Equality must stay Id-only, and a record's
    // generated structural equality would compare Status too, stranding every dictionary entry the
    // moment a device's status changed.
    internal NearbyDevice With(NearbyDeviceStatus status)
        => new(Id, Presence)
        {
            Gateway = Gateway,
            Status = status,
        };

    /// <summary>
    /// Determines whether the specified device is the same device as this one.
    /// </summary>
    /// <param name="other">The device to compare with the current device.</param>
    /// <returns>
    /// <see langword="true"/> if <paramref name="other"/> has the same <see cref="Id"/>; otherwise,
    /// <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// Compares <see cref="Id"/> only. Two snapshots of a device that merely changed status are
    /// still the same device.
    /// </remarks>
    public bool Equals(NearbyDevice? other)
        => other is not null
            && string.Equals(Id, other.Id, StringComparison.Ordinal);

    /// <summary>
    /// Returns the hash code for this device.
    /// </summary>
    /// <returns>A 32-bit signed integer hash code derived from <see cref="Id"/> alone.</returns>
    public override int GetHashCode() => StringComparer.Ordinal.GetHashCode(Id);

    /// <inheritdoc/>
    public override bool Equals(object? obj) => Equals(obj as NearbyDevice);

    /// <summary>
    /// Determines whether two devices are the same device.
    /// </summary>
    /// <param name="left">The first device.</param>
    /// <param name="right">The second device.</param>
    /// <returns>
    /// <see langword="true"/> when both are <see langword="null"/>, or both have the same
    /// <see cref="Id"/>.
    /// </returns>
    // Written out on purpose: without it, == falls back to reference equality, and two snapshots
    // of one device are always different references.
    public static bool operator ==(NearbyDevice? left, NearbyDevice? right)
        => left is null ? right is null : left.Equals(right);

    /// <summary>
    /// Determines whether two devices are different devices.
    /// </summary>
    /// <param name="left">The first device.</param>
    /// <param name="right">The second device.</param>
    /// <returns><see langword="true"/> when they do not have the same <see cref="Id"/>.</returns>
    public static bool operator !=(NearbyDevice? left, NearbyDevice? right) => !(left == right);

    /// <summary>
    /// Returns a string that represents the current device.
    /// </summary>
    /// <returns>
    /// A string containing the device's display name, identifier, and status, intended for
    /// diagnostic output rather than parsing. The name is omitted when the peer sent none.
    /// </returns>
    public override string ToString()
        => Presence.DisplayName.Length == 0
            ? $"[{Id}] {Status}"
            : $"{Presence.DisplayName} [{Id}] {Status}";
}
